/** Lower case without Polish letters, so „wąż” finds „waz” and the other way round. */
export const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/ł/g, 'l');

/** True when every word typed starts a word of the text (so „klucz” finds „klucze”). */
export function matches(query: string, text: string): boolean {
  const words = norm(text).split(/[^a-z0-9]+/).filter(Boolean);
  return norm(query)
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .every((q) => words.some((w) => w.startsWith(q)));
}
